"""
Implementation 2c: LLM-Compiled Rules.
Runs the pre-compiled, frozen Python modules generated by Gemini from the statutory rule text.
At runtime, NO LLM calls are made — zero latency overhead, pure deterministic execution.
"""

from __future__ import annotations

import time
from project_a.models import (
    TaxpayerInput,
    TaxResult,
    TaxComputation,
    DeductionBreakdown,
    City,
    AgeCategory,
)
from project_a import llm_compiled_rules_fy2024 as c24
from project_a import llm_compiled_rules_fy2025 as c25


def _run_compiled_fy24(user_input: TaxpayerInput) -> TaxResult:
    """Invokes the compiled FY 2024-25 module."""
    city_map = {
        City.METRO: c24.City.METRO,
        City.NON_METRO: c24.City.NON_METRO,
    }
    age_map = {
        AgeCategory.BELOW_60: c24.AgeCategory.BELOW_60,
        AgeCategory.SENIOR_60_TO_80: c24.AgeCategory.SENIOR_CITIZEN,
        AgeCategory.SUPER_SENIOR_ABOVE_80: c24.AgeCategory.SENIOR_CITIZEN,
    }

    # Map to compiled input schema
    comp_input = c24.TaxpayerInput(
        gross_salary=user_input.gross_salary,
        basic_salary=user_input.basic_salary,
        hra_received=user_input.hra_received,
        rent_paid=user_input.rent_paid_annual,
        city_type=city_map.get(user_input.city, c24.City.NON_METRO),
        age_category=age_map.get(user_input.age_category, c24.AgeCategory.BELOW_60),
        section_80c_investments=user_input.investment_80c,
        section_80ccd1b_nps=user_input.investment_80ccd_1b,
        section_80d_self_family=user_input.health_insurance_self,
        section_80d_parents=user_input.health_insurance_parents,
        section_24b_home_loan_interest=user_input.home_loan_interest,
        opt_for_new_regime=False,
    )

    comp_res = c24.compute_tax_compiled(comp_input)

    # Convert back to canonical TaxResult
    old_ded = DeductionBreakdown(
        standard_deduction=comp_res.old_regime_deductions.standard_deduction,
        hra_exemption=comp_res.old_regime_deductions.hra_exemption,
        section_80c=comp_res.old_regime_deductions.section_80c,
        section_80ccd_1b=comp_res.old_regime_deductions.section_80ccd1b,
        section_80d_self=comp_res.old_regime_deductions.section_80d,
        home_loan_interest_24b=comp_res.old_regime_deductions.section_24b,
        total=comp_res.old_regime_deductions.total_deductions,
    )
    new_ded = DeductionBreakdown(
        standard_deduction=comp_res.new_regime_deductions.standard_deduction,
        total=comp_res.new_regime_deductions.total_deductions,
    )

    old_comp = TaxComputation(
        gross_salary=comp_res.old_regime_computation.gross_salary,
        deductions=old_ded,
        taxable_income=comp_res.old_regime_computation.taxable_income,
        tax_on_slabs=comp_res.old_regime_computation.tax_before_rebate,
        rebate_87a=comp_res.old_regime_computation.rebate_87a,
        tax_after_rebate=comp_res.old_regime_computation.tax_after_rebate,
        surcharge=comp_res.old_regime_computation.surcharge,
        surcharge_after_relief=comp_res.old_regime_computation.surcharge,
        cess=comp_res.old_regime_computation.cess,
        total_tax=round(comp_res.old_regime_computation.total_tax_payable),
        clause_references={"source": "LLM-Compiled Rules FY2024 (c24)"},
    )

    new_comp = TaxComputation(
        gross_salary=comp_res.new_regime_computation.gross_salary,
        deductions=new_ded,
        taxable_income=comp_res.new_regime_computation.taxable_income,
        tax_on_slabs=comp_res.new_regime_computation.tax_before_rebate,
        rebate_87a=comp_res.new_regime_computation.rebate_87a,
        tax_after_rebate=comp_res.new_regime_computation.tax_after_rebate,
        surcharge=comp_res.new_regime_computation.surcharge,
        surcharge_after_relief=comp_res.new_regime_computation.surcharge,
        cess=comp_res.new_regime_computation.cess,
        total_tax=round(comp_res.new_regime_computation.total_tax_payable),
        clause_references={"source": "LLM-Compiled Rules FY2024 (c24)"},
    )

    rec = "New Tax Regime" if new_comp.total_tax < old_comp.total_tax else (
        "Old Tax Regime" if old_comp.total_tax < new_comp.total_tax else "Either Regime"
    )
    savings = abs(old_comp.total_tax - new_comp.total_tax)

    return TaxResult(
        old_regime=old_comp,
        new_regime=new_comp,
        recommended_regime=rec,
        savings=savings,
        explanation=f"LLM-compiled rules computed tax offline. Recommended: {rec} with savings of ₹{savings:,.0f}.",
    )


def _run_compiled_fy25(user_input: TaxpayerInput) -> TaxResult:
    """Invokes the compiled FY 2025-26 module."""
    # Build FY25 compiled input
    city_map = {
        City.METRO: c25.City.METRO,
        City.NON_METRO: c25.City.NON_METRO,
    }
    age_map = {
        AgeCategory.BELOW_60: c25.AgeCategory.BELOW_60,
        AgeCategory.SENIOR_60_TO_80: c25.AgeCategory.BETWEEN_60_AND_80,
        AgeCategory.SUPER_SENIOR_ABOVE_80: c25.AgeCategory.ABOVE_80,
    }

    self_non_senior = user_input.health_insurance_self if user_input.age_category == AgeCategory.BELOW_60 else 0.0
    self_senior = user_input.health_insurance_self if user_input.age_category != AgeCategory.BELOW_60 else 0.0
    parents_non_senior = user_input.health_insurance_parents if not user_input.parents_are_senior_citizens else 0.0
    parents_senior = user_input.health_insurance_parents if user_input.parents_are_senior_citizens else 0.0

    comp_input = c25.TaxpayerInput(
        gross_salary=user_input.gross_salary,
        basic_salary=user_input.basic_salary,
        hra_received=user_input.hra_received,
        rent_paid=user_input.rent_paid_annual,
        city_type=city_map.get(user_input.city, c25.City.NON_METRO),
        age_category=age_map.get(user_input.age_category, c25.AgeCategory.BELOW_60),
        opted_for_new_regime=False,
        section_80c_investments=user_input.investment_80c,
        section_80ccd1b_nps=user_input.investment_80ccd_1b,
        section_80d_self_family_non_senior=self_non_senior,
        section_80d_self_family_senior=self_senior,
        section_80d_parents_non_senior=parents_non_senior,
        section_80d_parents_senior=parents_senior,
        section_80d_preventive_health_checkup=0.0,
        section_24b_interest_on_housing_loan=user_input.home_loan_interest,
    )

    comp_res = c25.compute_tax_compiled(comp_input)

    old_comp = TaxComputation(
        gross_salary=comp_res.old_regime_computation.gross_total_income,
        taxable_income=comp_res.old_regime_computation.taxable_income,
        tax_on_slabs=comp_res.old_regime_computation.tax_before_rebate,
        rebate_87a=comp_res.old_regime_computation.rebate_87a,
        tax_after_rebate=comp_res.old_regime_computation.tax_after_rebate,
        surcharge=comp_res.old_regime_computation.surcharge,
        surcharge_after_relief=comp_res.old_regime_computation.surcharge,
        cess=comp_res.old_regime_computation.health_education_cess,
        total_tax=round(comp_res.old_regime_computation.total_tax_liability),
        clause_references={"source": "LLM-Compiled Rules FY2025 (c25)"},
    )

    new_comp = TaxComputation(
        gross_salary=comp_res.new_regime_computation.gross_total_income,
        taxable_income=comp_res.new_regime_computation.taxable_income,
        tax_on_slabs=comp_res.new_regime_computation.tax_before_rebate,
        rebate_87a=comp_res.new_regime_computation.rebate_87a,
        tax_after_rebate=comp_res.new_regime_computation.tax_after_rebate,
        surcharge=comp_res.new_regime_computation.surcharge,
        surcharge_after_relief=comp_res.new_regime_computation.surcharge,
        cess=comp_res.new_regime_computation.health_education_cess,
        total_tax=round(comp_res.new_regime_computation.total_tax_liability),
        clause_references={"source": "LLM-Compiled Rules FY2025 (c25)"},
    )

    rec = "New Tax Regime" if new_comp.total_tax < old_comp.total_tax else (
        "Old Tax Regime" if old_comp.total_tax < new_comp.total_tax else "Either Regime"
    )
    savings = abs(old_comp.total_tax - new_comp.total_tax)

    return TaxResult(
        old_regime=old_comp,
        new_regime=new_comp,
        recommended_regime=rec,
        savings=savings,
        explanation=f"LLM-compiled rules for FY25 computed tax offline. Recommended: {rec}.",
    )


def compute_tax_llm_compiled(user_input: TaxpayerInput, fy: str = "2024-25") -> TaxResult:
    """
    Computes tax using LLM-compiled executable rules.
    Runs entirely offline with 0 API calls.
    """
    if fy == "2025-26":
        return _run_compiled_fy25(user_input)
    return _run_compiled_fy24(user_input)
